#!/usr/bin/env node
// Writes .env.local (git-ignored) so the app talks to the LOCAL gateway with the local synthetic
// keys from .local/stack.json. AI stays disabled and no OpenAI key is written.
// An existing .env.local that points anywhere else is never overwritten unless --force is given,
// in which case it is first renamed to .env.local.backup-<timestamp> (also git-ignored).
import fs from "node:fs";
import { GATEWAY_URL, PATHS, fail, log, readStack, runMain } from "./lib.mjs";

await runMain(async () => {
  const stack = readStack();
  if (!stack) fail("Missing .local/stack.json. Start the stack first: node scripts/local-stack/start.mjs");
  if (fs.existsSync(PATHS.envLocal)) {
    const current = fs.readFileSync(PATHS.envLocal, "utf8");
    const url = /^NEXT_PUBLIC_SUPABASE_URL=(.*)$/m.exec(current)?.[1]?.trim() ?? "";
    if (url !== GATEWAY_URL) {
      if (!process.argv.includes("--force")) fail(`.env.local exists and points to "${url || "(unset)"}", not the local gateway. Re-run with --force to back it up and replace it.`);
      const backup = `${PATHS.envLocal}.backup-${new Date().toISOString().replace(/[:.]/g, "-")}`;
      fs.renameSync(PATHS.envLocal, backup);
      log(`Moved the previous .env.local to ${backup}`);
    }
  }
  fs.writeFileSync(PATHS.envLocal, [
    "# Generated by scripts/local-stack/env.mjs for the LOCAL Supabase-compatible stack.",
    "# Synthetic local-only keys (see .local/stack.json). Never use real project credentials here.",
    `NEXT_PUBLIC_SUPABASE_URL=${GATEWAY_URL}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${stack.publishableKey}`,
    `SUPABASE_SECRET_KEY=${stack.secretKey}`,
    "AI_ENABLED=false",
    "OPENAI_API_KEY=",
    "",
  ].join("\n"), { mode: 0o600 });
  log(`Wrote ${PATHS.envLocal} -> ${GATEWAY_URL} (AI_ENABLED=false). Restart the app after changes.`);
});
